"""Export the quick start's rules for the web: apps/web/lib/try-rules.json.

The public site (Render, Node only) runs the same Test drive as `python -m engine try` (engine/try_it.py). This writes
the one source of truth it needs, so the two never drift: the role lanes, level rules, specialty words, keyword
vocabulary (engine/tailoring/keywords.TECH + try_it.DOMAIN, with the same patterns), JD boilerplate cut, score weights,
the US / company patterns from engine/discovery/filters.py, and where the sample boards live (the list itself stays
only in boards.example.txt, the one file the privacy gate allows to name companies).
tests/test_try_rules.py fails when the committed JSON is stale; rerun this script then.

    python scripts/try_rules.py
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "apps", "web", "lib", "try-rules.json")


def rules():
    sys.path.insert(0, ROOT)
    from engine import try_it as t
    from engine.discovery import filters as f
    from engine.tailoring.keywords import TECH
    terms = {}
    for name, extra in {**TECH, **t.DOMAIN}.items():  # the same pattern list try_it.terms_table() compiles
        import re
        terms[name] = t.OVERRIDE.get(name) or [r"(?<![a-z0-9+#.])" + re.escape(name.lower()) + r"(?![a-z0-9+#])"] + list(extra)
    return {
        "_": "generated by scripts/try_rules.py from engine/try_it.py + engine/discovery/filters.py + engine/tailoring/keywords.py; do not edit",
        "lanes": t.LANES, "resume_title": t.RESUME_TITLE, "levels": t.LEVELS, "specialty": t.SPECIALTY, "student": t.STUDENT,
        "boilerplate": t.BOILERPLATE, "weights": t.WEIGHTS, "terms": terms,
        "exclude_companies": f.DEFAULT_DOMAIN["exclude_companies"],
        "us_states": sorted(f.US_STATES), "us_words": f.US_WORDS.pattern, "non_us": f.NON_US.pattern,
        "non_software": f.NON_SOFTWARE.pattern, "software_words": f.SOFTWARE_WORDS.pattern,
        "boards_file": "engine/discovery/boards.example.txt", "boards_n": 40, "days": 30,
    }


def text():
    return json.dumps(rules(), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    open(OUT, "w", encoding="utf-8", newline="\n").write(text())
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
