"""Export the quick start's rules for the web: apps/web/lib/try-rules.json.

The public site (Render, Node only) runs the same "Try it" ranking as `python -m engine try` (engine/try_it.py). This
writes the one source of truth it needs, so the two never drift: the default fit gate (DEFAULT_DOMAIN and the US /
non-software / non-engineering patterns from engine/discovery/filters.py), the skill families from engine/try_it.py,
and where the sample boards live (the list itself stays only in boards.example.txt, the one file the privacy
gate allows to name companies). tests/test_try_rules.py fails when the committed JSON is stale; rerun this script then.

    python scripts/try_rules.py
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "apps", "web", "lib", "try-rules.json")


def rules():
    sys.path.insert(0, ROOT)
    from engine import try_it
    from engine.discovery import filters as f
    d = f.DEFAULT_DOMAIN
    return {
        "_": "generated by scripts/try_rules.py from engine/try_it.py + engine/discovery/filters.py; do not edit",
        "include_titles": d["include_titles"], "exclude_titles": d["exclude_titles"],
        "exclude_companies": d["exclude_companies"], "require_us": d["require_us"],
        "us_states": sorted(f.US_STATES), "us_words": f.US_WORDS.pattern, "non_us": f.NON_US.pattern,
        "non_software": f.NON_SOFTWARE.pattern, "software_words": f.SOFTWARE_WORDS.pattern,
        "not_engineering": f.NOT_ENGINEERING.pattern,
        "families": {k: {"title": t, "resume": r} for k, (t, r) in try_it.FAMILIES.items()},
        "boards_file": "engine/discovery/boards.example.txt", "boards_n": 40,
    }


def text():
    return json.dumps(rules(), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    open(OUT, "w", encoding="utf-8", newline="\n").write(text())
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
