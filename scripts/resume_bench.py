"""Benchmark the resume classifier (engine/resume_nlp.py) on the held-out set (tests/resume_bench.py).

Reports accuracy, per-class precision / recall / F1, macro and weighted averages, the confusion matrix, and the
posting-title accuracy (tests/resume_corpus.py TITLES); writes apps/web/lib/resume-bench.json for the site's pipeline
page. "unclassified" is a class like the others: a resume the engine should refuse to guess on.

    python scripts/resume_bench.py          # print the report and write the JSON
    python scripts/resume_bench.py --check  # exit 1 when the committed JSON is stale (tests use this)
"""
import datetime, json, os, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "apps", "web", "lib", "resume-bench.json")
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tests"))


import re

HEADERS = r"(?im)^\s*(summary|profile|experience|work history|professional experience|work|skills|core competencies|education|certifications|licenses|projects|awards[^\n]*|teaching experience|clinical experience|research[^\n]*experience)\s*$"
NOISE = "Team player. Microsoft Word. Driver's license. References available on request. Hobbies: hiking, chess."
PERTURB = {  # name -> mutation of a resume's text
    "UPPER CASE": lambda t: t.upper(),
    "lower case": lambda t: t.lower(),
    "one line (no line breaks)": lambda t: " ".join(t.split()),
    "no section headers": lambda t: re.sub(HEADERS, "", t),
    "sections reversed": lambda t: "\n".join(reversed(t.split("\n"))),
    "noise lines added": lambda t: t + "\n" + NOISE,
    "misleading employer names": lambda t: re.sub(r"(\|\s*|@\s*|\bat\s+)([A-Z][\w&'.]+(?:\s[A-Z][\w&'.]+)*)", r"\1Software Sales Hospital Inc", t),
}


def evaluate():
    from engine import resume_nlp as N
    from resume_bench import BENCH
    from resume_corpus import CORPUS, TITLES
    classes = sorted(set(N.FAMILIES) | {"unclassified"})
    pairs, misses = [], []
    t0 = time.perf_counter()
    for want, text in BENCH:
        got = N.analyze(text, explain=False)["label"]
        pairs.append((want, got))
        if got != want:
            misses.append({"want": want, "got": got, "start": " ".join(text.split())[:70]})
    ms = (time.perf_counter() - t0) * 1000 / max(1, len(BENCH))
    labels = [c for c in classes if any(c in p for p in pairs)]
    cm = [[sum(1 for w, g in pairs if w == a and g == b) for b in labels] for a in labels]
    per = []
    for i, c in enumerate(labels):
        tp = cm[i][i]
        fp = sum(cm[r][i] for r in range(len(labels))) - tp
        fn = sum(cm[i]) - tp
        p = tp / (tp + fp) if tp + fp else 0.0
        r = tp / (tp + fn) if tp + fn else 0.0
        f = 2 * p * r / (p + r) if p + r else 0.0
        per.append({"class": c, "precision": round(p, 3), "recall": round(r, 3), "f1": round(f, 3), "support": sum(cm[i])})
    sup = [x for x in per if x["support"]]
    n = len(pairs)
    macro = {k: round(sum(x[k] for x in sup) / len(sup), 3) for k in ("precision", "recall", "f1")}
    weighted = {k: round(sum(x[k] * x["support"] for x in sup) / n, 3) for k in ("precision", "recall", "f1")}
    # robustness: the same held-out resumes, mutated the ways real pastes arrive; the label must not move
    rob = {}
    for name, fn in PERTURB.items():
        ok = sum(N.analyze(fn(t), explain=False)["label"] == w for w, t in BENCH)
        rob[name] = round(ok / n, 3)
    dev = sum(N.analyze(t, explain=False)["label"] == w for w, t in CORPUS)
    titles = sum((N.classify_title(t) or [""])[0] == w for t, w in TITLES)
    return {"_": "generated by scripts/resume_bench.py; do not edit",
            "set": "tests/resume_bench.py (held out: not used to tune the vocabulary)",
            "n": n, "classes": len(sup), "accuracy": round(sum(w == g for w, g in pairs) / n, 3),
            "macro": macro, "weighted": weighted, "per_class": per, "labels": labels, "confusion": cm,
            "misses": misses, "ms_per_resume": round(ms, 2), "robustness": rob,
            "dev": {"set": "tests/resume_corpus.py (development: used to tune)", "n": len(CORPUS), "correct": dev},
            "titles": {"n": len(TITLES), "correct": titles}}


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    r = evaluate()
    stable = json.dumps({k: v for k, v in r.items() if k != "ms_per_resume"}, sort_keys=True)
    if "--check" in argv:
        try:
            old = json.load(open(OUT, encoding="utf-8"))
        except (OSError, ValueError):
            sys.exit("resume-bench.json missing: run python scripts/resume_bench.py")
        if json.dumps({k: v for k, v in old.items() if k not in ("ms_per_resume", "run")}, sort_keys=True) != stable:
            sys.exit("resume-bench.json is stale: run python scripts/resume_bench.py")
        print("resume-bench.json current")
        return
    r["run"] = datetime.date.today().isoformat()
    json.dump(r, open(OUT, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print(f"held-out: {r['n']} resumes, {r['classes']} classes | accuracy {r['accuracy']:.1%} | macro P {r['macro']['precision']:.3f} "
          f"R {r['macro']['recall']:.3f} F1 {r['macro']['f1']:.3f} | weighted F1 {r['weighted']['f1']:.3f} | {r['ms_per_resume']} ms/resume")
    print(f"dev set {r['dev']['correct']}/{r['dev']['n']} | posting titles {r['titles']['correct']}/{r['titles']['n']}")
    for m in r["misses"]:
        print(f"  miss: want {m['want']!r} got {m['got']!r}: {m['start']}")
    print("wrote " + os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
